test("commit matches Cairo vectors", () => {
  for (const [a, b, x, y] of VECTORS) {
    const c = commit(a, b);
    assert.equal(c.x, x, `x for commit(${a},${b})`);
    assert.equal(c.y, y, `y for commit(${a},${b})`);
  }
});

test("additive homomorphism", () => {
  const c1 = commit(30n, 5n);
  const c2 = commit(40n, 6n);
  const sum = addCommitments(c1, c2);
  assert.ok(commitmentsEqual(sum, commit(70n, 11n)));
});

test("aggregate binds total amount and blinding", () => {
  const amounts = [100n, 200n, 300n, 400n];
  const blindings = [11n, 22n, 33n, 44n];
  const { total, totalAmount, totalBlinding } = aggregate(amounts, blindings);
  assert.equal(totalAmount, 1000n);
  // total commitment must equal commit(Σamount, Σblinding) — the on-chain check
  assert.ok(commitmentsEqual(total, commit(totalAmount, totalBlinding)));
});
